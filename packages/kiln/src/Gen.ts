import { Effect } from "effect"
import { existsSync, lstatSync, mkdirSync, readlinkSync, realpathSync, rmSync, symlinkSync, writeFileSync } from "node:fs"
import { delimiter, join, resolve } from "node:path"
import * as Exec from "./Exec.ts"

/** Kiln's SDK next to this file: in a checkout `<repo>/sdk/node_modules`, in the Nix package the same layout. */
export const sdkPath = resolve(import.meta.dirname, "../../../sdk/node_modules")

/**
 * `.kiln/tsconfig.json`. The compiler options come from the SDK through `.kiln/node_modules`, so a
 * change to them reaches every project with the next Kiln instead of the next `kiln gen`.
 */
export const tsconfig = { extends: "@kiln/tsconfig", include: ["*.ts"] }

const names = (dir: string, output: string, system: string) =>
  Exec.run(["nix", "eval", "--json", `${dir}#${output}.${system}`, "--apply", "builtins.attrNames"], { cwd: dir }).pipe(
    Effect.map((json) => JSON.parse(json) as ReadonlyArray<string>),
    Effect.orElseSucceed(() => [] as ReadonlyArray<string>),
  )

const standard = `import { Project } from "@kiln/std"
import { flake } from "./flake.ts"

export default Project.standard({ flake })
`

/**
 * `kiln gen`: writes `.kiln/flake.ts` from the flake's outputs, a tsconfig for editors, and links
 * `.kiln/node_modules` to Kiln's SDK so `@kiln/core`, `@kiln/std` and `effect` resolve. A repository
 * without `.kiln/ci.ts` gets the standard pipeline.
 */
export const gen = (repo: string, system: string) =>
  Effect.gen(function*() {
    const dir = resolve(repo)
    const kiln = join(dir, ".kiln")
    mkdirSync(kiln, { recursive: true })
    const [packages, checks, devShells] = yield* Effect.all(
      [names(dir, "packages", system), names(dir, "checks", system), names(dir, "devShells", system)],
      { concurrency: "unbounded" },
    )
    const list = (xs: ReadonlyArray<string>) => `[${xs.map((x) => JSON.stringify(x)).join(", ")}]`
    writeFileSync(
      join(kiln, "flake.ts"),
      `// Generated by \`kiln gen\` from the flake's outputs. Run it again after adding or renaming outputs.
import { Flake } from "@kiln/core"

export const flake = Flake.make({
  packages: ${list(packages)},
  checks: ${list(checks)},
  devShells: ${list(devShells)},
})
`,
    )
    writeFileSync(join(kiln, "tsconfig.json"), `${JSON.stringify(tsconfig, null, 2)}\n`)
    writeFileSync(join(kiln, ".gitignore"), "node_modules\n")
    linkCheckout(kiln)
    const created = !existsSync(join(kiln, "ci.ts"))
    if (created) writeFileSync(join(kiln, "ci.ts"), standard)
    return { packages, checks, devShells, created }
  })

/**
 * The SDK as seen through the profile that put this Kiln on PATH, such as
 * `/run/current-system/sw/lib/kiln/sdk/node_modules`. A checkout linked there follows Kiln upgrades,
 * while a link to the store path breaks once a garbage collection removes an older Kiln. Without such
 * a profile, as in a checkout of Kiln itself, the SDK's own path.
 */
export const stableSdk = (sdk: string, path: string): string => {
  const real = realpathSync(sdk)
  for (const dir of path.split(delimiter)) {
    if (dir === "") continue
    const candidate = resolve(dir, "../lib/kiln/sdk/node_modules")
    if (existsSync(candidate) && realpathSync(candidate) === real) return candidate
  }
  return sdk
}

/** Points a checkout's `.kiln/node_modules` at the SDK of the Kiln on PATH. */
export const linkCheckout = (kilnDir: string) => link(join(kilnDir, "node_modules"), stableSdk(sdkPath, process.env.PATH ?? ""))

export const link = (path: string, target: string) => {
  if (existsSync(path) || isLink(path)) {
    if (isLink(path) && readlinkSync(path) === target) return
    rmSync(path, { recursive: true, force: true })
  }
  symlinkSync(target, path)
}

const isLink = (path: string) => {
  try {
    return lstatSync(path).isSymbolicLink()
  } catch {
    return false
  }
}
