"""Writes js/plans.js: what tsc and calder plan say about every arrangement the hero allows.

Usage: python3 -I site/scripts/plans.py   (from the repository root, after pnpm install)

It runs the repository's own tsc and Calder on a copy of site/example. typecheck, test and site may
sit in either rule, deploy sits in the push rule, and for each arrangement it also records what
happens when deploy is put into the pull-request rule. Run it again when Calder's output changes.
"""

import itertools
import json
import os
import pathlib
import shutil
import subprocess
import tempfile

repo = pathlib.Path.cwd()
site = repo / "site"
tsc = [str(repo / "node_modules/.bin/tsc"), "-p", ".calder", "--noEmit"]
calder = ["bun", str(repo / "packages/calder/src/main.ts"), "plan", "--event"]
events = {"pr:7": "pr", "push:main": "push", "check": "check"}

# The drawing's order: the pull-request rule as setup dependents, builds, actions; the push rule
# mirrored, so site and deploy meet at the rules' boundary.
kind = {"typecheck": 0, "test": 0, "site": 1, "deploy": 2}
order = ["typecheck", "test", "site", "deploy"]


def pr_order(names):
    return sorted(names, key=lambda n: (kind[n], order.index(n)))


def push_order(names):
    return sorted(names, key=lambda n: ((kind[n] - 1) % 3, order.index(n)))


def line34(names):
    return f"    On.pullRequest([{', '.join(names)}]),"


def line35(names):
    return f'    On.push("main", [{", ".join(names)}]),'


with tempfile.TemporaryDirectory() as scratch:
    root = pathlib.Path(scratch) / "example"
    shutil.copytree(site / "example", root)
    os.symlink(repo / "sdk/node_modules", root / ".calder/node_modules")
    # calder plan checks the pipeline's paths against the committed tree.
    git = ["git", "-c", "user.name=calder", "-c", "user.email=calder@example.com"]
    subprocess.run(["git", "init", "-q"], cwd=root, check=True)
    subprocess.run(["git", "add", "-A"], cwd=root, check=True)
    subprocess.run([*git, "commit", "-q", "-m", "example"], cwd=root, check=True)

    ci = root / ".calder/ci.ts"
    lines = ci.read_text().split("\n")
    assert lines[33] == line34(["typecheck", "test", "site"]), lines[33]
    assert lines[34] == line35(["deploy"]), lines[34]

    def run(cmd):
        p = subprocess.run(cmd, cwd=root, capture_output=True, text=True)
        return {"exit": p.returncode, "out": (p.stdout + p.stderr).rstrip("\n")}

    def outcome(pr, push):
        new = lines.copy()
        new[33], new[34] = line34(pr), line35(push)
        ci.write_text("\n".join(new))
        return {
            "pr": pr,
            "push": push,
            "line34": line34(pr),
            "line35": line35(push),
            "tsc": run(tsc),
            "plans": {name: run([*calder, event]) for event, name in events.items()},
        }

    arrangements = {}
    for places in itertools.product(["pr", "push"], repeat=3):
        where = dict(zip(["typecheck", "test", "site"], places), deploy="push")
        pr = pr_order([n for n in order if where[n] == "pr"])
        push = push_order([n for n in order if where[n] == "push"])
        arrangements[",".join(places)] = {
            "ok": outcome(pr, push),
            "refused": outcome(pr_order(pr + ["deploy"]), [n for n in push if n != "deploy"]),
        }
        print(",".join(places), "done")

body = json.dumps(arrangements, indent=1, ensure_ascii=False)
(site / "js/plans.js").write_text(
    "// Generated by site/scripts/plans.py from real runs of tsc and calder plan on a copy of\n"
    "// site/example, one per arrangement of typecheck, test and site (keyed in that order).\n"
    f"export const ARRANGEMENTS = {body}\n"
)
